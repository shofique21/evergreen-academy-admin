<script setup lang="ts">
import { ref } from 'vue'
import { useRouter } from 'vue-router'
import { useToast } from 'primevue/usetoast'
import Button from 'primevue/button'
import InputText from 'primevue/inputtext'
import { FormField } from '@/components/forms'
import { AppAlert } from '@/components/notifications'

const router = useRouter()
const toast = useToast()

const mfaCode = ref('')
const isBackupCode = ref(false)
const backupCode = ref('')
const loading = ref(false)
const errorMessage = ref<string | null>(null)

async function verifyMfa() {
  errorMessage.value = null
  const code = isBackupCode.value ? backupCode.value.trim() : mfaCode.value.trim()
  if (!code) {
    errorMessage.value = isBackupCode.value
      ? 'Please enter your emergency recovery code.'
      : 'Please enter the 6-digit authenticator code.'
    return
  }

  loading.value = true
  try {
    // Simulate / execute MFA validation against API
    await new Promise((resolve) => setTimeout(resolve, 600))
    toast.add({
      severity: 'success',
      summary: 'Identity Verified',
      detail: 'Two-factor authentication successful.',
      life: 3000,
    })
    router.push('/dashboard')
  } catch (err: any) {
    errorMessage.value = err.response?.data?.message || 'Invalid verification code. Please try again.'
  } finally {
    loading.value = false
  }
}
</script>

<template>
  <div class="mfa-card">
    <div class="mfa-header">
      <div class="shield-icon-wrap">
        <i class="pi pi-shield"></i>
      </div>
      <h2 class="mfa-title">Two-Factor Authentication</h2>
      <p class="mfa-subtitle">
        {{
          isBackupCode
            ? 'Enter one of your emergency recovery codes to authenticate.'
            : 'Enter the 6-digit code generated by your Authenticator app (Google Authenticator, Authy).'
        }}
      </p>
    </div>

    <AppAlert
      v-if="errorMessage"
      severity="danger"
      :message="errorMessage"
      dismissible
      class="mb-4"
      @dismiss="errorMessage = null"
    />

    <form @submit.prevent="verifyMfa" class="mfa-form">
      <FormField
        v-if="!isBackupCode"
        id="mfaCode"
        label="6-Digit Authenticator Code"
        required
      >
        <InputText
          id="mfaCode"
          v-model="mfaCode"
          placeholder="123456"
          maxlength="6"
          class="mfa-code-input text-center font-mono tracking-widest text-xl"
          autocomplete="one-time-code"
          autofocus
        />
      </FormField>

      <FormField
        v-else
        id="backupCode"
        label="Emergency Recovery Code"
        required
      >
        <InputText
          id="backupCode"
          v-model="backupCode"
          placeholder="XXXXX-XXXXX"
          class="backup-code-input text-center font-mono text-base"
        />
      </FormField>

      <Button
        type="submit"
        label="Verify Identity"
        icon="pi pi-check"
        :loading="loading"
        class="w-full mt-2"
        severity="primary"
      />

      <div class="toggle-mode-row">
        <button
          type="button"
          class="text-link"
          @click="isBackupCode = !isBackupCode"
        >
          {{ isBackupCode ? 'Use 6-digit authenticator code' : 'Lost access? Use emergency recovery code' }}
        </button>
      </div>

      <div class="back-link-row">
        <router-link to="/login" class="back-link">
          <i class="pi pi-arrow-left"></i>
          <span>Back to sign in</span>
        </router-link>
      </div>
    </form>
  </div>
</template>

